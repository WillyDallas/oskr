#!/usr/bin/env bash
# oskr-setup.sh — workspace-tier bootstrap verbs (skeleton + global config).
# Pure filesystem/JSON; touches NO forge, so it stays OUTSIDE the backend seam
# (no gh/curl). The interactive walkthrough lives in skills/oskr-setup/SKILL.md,
# which gathers config then calls these verbs.
#
# Workspace CREATION anchors at an explicit dir (default $PWD) — it does NOT use
# the upward .oskr/ resolver (blacksmith_workspace_dir), which only FINDS an
# existing workspace. Secrets are NEVER written here (creds live in .env / gh).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

_setup_die() { echo "[oskr-setup] $1" >&2; exit 1; }

# Create the workspace skeleton and first-create an empty project registry.
# Idempotent on dirs (mkdir -p) and on the registry (first-create only). The
# brain is stamped via bin/hjarne-skeleton.sh — the canonical populator, itself
# idempotent and non-clobbering — so a fresh workspace gets a STAMPED hjarne/
# (schema.md/README.md/todo.md/log.md + wiki/raw/projects), never a bare dir.
#   skeleton <workspace_dir>
oskr_setup_skeleton() {
  local ws="${1:-$PWD}"
  mkdir -p "$ws/.oskr" "$ws/projects" "$ws/learning"
  bash "$SCRIPT_DIR/hjarne-skeleton.sh" "$ws/hjarne" >/dev/null
  if [[ ! -f "$ws/.oskr/registry.json" ]]; then
    printf '%s\n' '{"projects": []}' > "$ws/.oskr/registry.json"
  fi
}

# Write .oskr/config.json from environment-supplied NON-SECRET values. Guarded:
# refuses if a config already exists so re-running setup never clobbers a live
# workspace. Credentials are NOT written here — they live in the workspace .env
# (FORGEJO_TOKEN) / gh keychain; this records only backend selection + coords.
#   write-config <workspace_dir>
# Env: OSKR_FORGE (default github)  OSKR_BASE_BRANCH (default main)
#      OSKR_GITHUB_OWNER (optional) OSKR_FORGEJO_BASE_URL (optional)
oskr_setup_write_config() {
  local ws="${1:-$PWD}" cfg
  [[ -d "$ws/.oskr" ]] || _setup_die "no .oskr/ at $ws — run 'skeleton' first"
  cfg="$ws/.oskr/config.json"
  [[ -f "$cfg" ]] && _setup_die "workspace already configured ($cfg); not clobbering"
  jq -n \
    --arg forge "${OSKR_FORGE:-github}" \
    --arg base  "${OSKR_BASE_BRANCH:-main}" \
    --arg owner "${OSKR_GITHUB_OWNER:-}" \
    --arg furl  "${OSKR_FORGEJO_BASE_URL:-}" \
    '{version: 1, forge: $forge, base_branch: $base,
      github: {owner: $owner}, forgejo: {base_url: $furl}}' > "$cfg.tmp" \
    && mv "$cfg.tmp" "$cfg"
  jq . "$cfg" >/dev/null || _setup_die "wrote malformed config"
}

# One-shot: skeleton then write-config. The single verb the skill calls after it
# gathers inputs.  bootstrap <workspace_dir>
oskr_setup_bootstrap() {
  local ws="${1:-$PWD}"
  oskr_setup_skeleton "$ws"
  oskr_setup_write_config "$ws"
}

# --- execution arms (disk-touching) -----------------------------------------
# The verbs above scaffold the workspace (dirs + JSON). The two below mutate git
# state and the projects/ tree: git-init puts the workspace under version control
# and sets (never pushes) the origin remote; rehydrate re-clones managed projects
# from the registry. Both stay OUTSIDE the backend seam — `git init`/`remote add`/
# `git clone` touch no forge API (no gh/curl); pushing is a manual/smoke step.

# _oskr_setup_gitignore_body — emit the exact .gitignore contract on stdout.
# Ignored: secrets + the cloned projects/ tree + raw brain sources + OS cruft.
# Everything else stays tracked (.oskr/config.json, .oskr/registry.json,
# hjarne/wiki/**, learning/**, memory/**, docs).
_oskr_setup_gitignore_body() {
  cat <<'GITIGNORE'
# oskr workspace .gitignore — generated by `oskr-setup.sh git-init`.
# Secrets never enter version control.
.env
*.env
*.key
*.pem
secrets/
# Managed projects are cloned, not vendored — `rehydrate` reconstructs them.
projects/
# Brain raw sources stay machine-local; only the distilled wiki is tracked.
hjarne/raw/
# OS cruft
.DS_Store
GITIGNORE
}

# _oskr_setup_workspace_remote <workspace_dir> — echo the composed origin URL per
# precedence. Pure string composition; no network. NOTE: the workspace repo slug
# (OSKR_WORKSPACE_SLUG) is DISTINCT from config.github.owner (the default owner
# for NEW PROJECTS, not the workspace repo).
_oskr_setup_workspace_remote() {
  local ws="$1" cfg forge base slug
  # 1. Full-URL escape hatch — used verbatim, before any config read.
  if [[ -n "${OSKR_WORKSPACE_REMOTE:-}" ]]; then
    printf '%s' "$OSKR_WORKSPACE_REMOTE"; return 0
  fi
  slug="${OSKR_WORKSPACE_SLUG:-squirrlylabs/workspace}"
  cfg="$ws/.oskr/config.json"
  forge="github"
  [[ -f "$cfg" ]] && forge="$(jq -r '.forge // "github"' "$cfg")"
  case "$forge" in
    forgejo)
      base="$(jq -r '.forgejo.base_url // ""' "$cfg")"
      [[ -n "$base" ]] || _setup_die "git-init: forge=forgejo but .forgejo.base_url is empty in $cfg"
      printf '%s/%s.git' "${base%/}" "$slug" ;;
    *)
      printf 'https://github.com/%s.git' "$slug" ;;
  esac
}

# git-init <workspace_dir> — make the workspace a git repo (idempotent), write the
# .gitignore contract, configure the `origin` workspace remote, and land an initial
# commit with an INJECTED identity so it works on a bare machine with no ambient
# user.email/user.name. NEVER pushes — that is a manual/smoke step.
oskr_setup_git_init() {
  local ws="${1:-$PWD}" remote
  [[ -d "$ws/.oskr" ]] || _setup_die "no .oskr/ at $ws — run 'skeleton' first"

  git -C "$ws" init -q
  _oskr_setup_gitignore_body > "$ws/.gitignore"

  remote="$(_oskr_setup_workspace_remote "$ws")"
  if git -C "$ws" remote get-url origin >/dev/null 2>&1; then
    git -C "$ws" remote set-url origin "$remote"
  else
    git -C "$ws" remote add origin "$remote"
  fi

  git -C "$ws" add -A
  git -C "$ws" \
    -c user.email="${OSKR_GIT_EMAIL:-oskr@squirrlylabs.local}" \
    -c user.name="${OSKR_GIT_NAME:-oskr}" \
    commit -q -m "chore(workspace): oskr workspace baseline" 2>/dev/null || true
}

# _oskr_setup_clone_url <workspace_dir> <registry_index> — echo the clone URL for
# one registry entry, from THAT entry's coords (projects may live on different
# forges). Pure string composition; no network.
#   github  entry: https://github.com/<owner>/<repo>.git
#   forgejo entry: <ssh_base>/<owner>/<repo>.git when the workspace config sets
#                  forgejo.ssh_base AND the entry is on the config's instance;
#                  else <base_url without trailing />/<owner>/<repo>.git
_oskr_setup_clone_url() {
  local ws="$1" i="$2" reg forge owner repo base cfg_base ssh_base
  reg="$ws/.oskr/registry.json"
  forge="$(jq -r ".projects[$i].forge // \"github\"" "$reg")"
  case "$forge" in
    github)
      owner="$(jq -r ".projects[$i].github.owner" "$reg")"
      repo="$(jq -r ".projects[$i].github.repo" "$reg")"
      printf 'https://github.com/%s/%s.git' "$owner" "$repo" ;;
    forgejo)
      base="$(jq -r ".projects[$i].forgejo.base_url" "$reg")"
      owner="$(jq -r ".projects[$i].forgejo.owner" "$reg")"
      repo="$(jq -r ".projects[$i].forgejo.repo" "$reg")"
      cfg_base="$(jq -r '.forgejo.base_url // ""' "$ws/.oskr/config.json" 2>/dev/null || true)"
      ssh_base="$(jq -r '.forgejo.ssh_base // ""' "$ws/.oskr/config.json" 2>/dev/null || true)"
      if [[ -n "$ssh_base" && "${base%/}" == "${cfg_base%/}" ]]; then
        printf '%s/%s/%s.git' "${ssh_base%/}" "$owner" "$repo"
      else
        printf '%s/%s/%s.git' "${base%/}" "$owner" "$repo"
      fi ;;
    *) _setup_die "rehydrate: entry $i has unknown forge '$forge'" ;;
  esac
}

# rehydrate <workspace_dir> [--dry-run] [--only <name>]... — reconstruct the
# managed-project tree by cloning .oskr/registry.json entries into
# projects/<name> (URLs per _oskr_setup_clone_url). --only (repeatable) limits it
# to the named projects; an unknown name dies before anything is cloned.
# --dry-run prints, per selected entry, whether it is present or would be cloned,
# and touches no disk. Existing projects/<name>/.git are skipped (idempotent;
# never re-clones or overwrites).
oskr_setup_rehydrate() {
  local ws="${1:-$PWD}"; [[ "$#" -gt 0 ]] && shift
  local dry_run=0 only=""
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --dry-run) dry_run=1; shift ;;
      --only)
        [[ $# -ge 2 ]] || _setup_die "rehydrate: --only requires a project name"
        only="${only:+$only }$2"; shift 2 ;;
      *) _setup_die "rehydrate: unknown flag '$1'" ;;
    esac
  done
  local reg="$ws/.oskr/registry.json"
  [[ -f "$reg" ]] || _setup_die "rehydrate: no registry at $reg — run 'skeleton' first"

  local want
  for want in $only; do
    jq -e --arg n "$want" '.projects[] | select(.name == $n)' "$reg" >/dev/null \
      || _setup_die "rehydrate: no project '$want' in registry"
  done

  local n i=0 name url dest
  n="$(jq '.projects | length' "$reg")"
  while [[ "$i" -lt "$n" ]]; do
    name="$(jq -r ".projects[$i].name" "$reg")"
    dest="$ws/projects/$name"
    if [[ -n "$only" ]]; then
      case " $only " in
        *" $name "*) ;;
        *) i=$((i + 1)); continue ;;
      esac
    fi
    url="$(_oskr_setup_clone_url "$ws" "$i")"

    if [[ -d "$dest/.git" ]]; then
      printf 'rehydrate: projects/%s present\n' "$name"
    elif [[ "$dry_run" -eq 1 ]]; then
      printf 'rehydrate: would clone %s -> projects/%s\n' "$url" "$name"
    else
      git clone -q "$url" "$dest"
    fi
    i=$((i + 1))
  done
}

# save <workspace_dir> [-m <msg>] — identity-injected checkpoint commit of the
# workspace control plane (default message "oskr save"). Sweeps everything
# (add -A): the sweep is DELIBERATE — untracked non-secret root junk rides
# along, acceptable for a control-plane repo because the .gitignore contract
# keeps secrets and projects/ out. No-op (exit 0, HEAD unchanged) on a clean
# tree. Local-only: publishing is the skill's confirmed final phase.
oskr_setup_save() {
  local ws="${1:-$PWD}"; [[ "$#" -gt 0 ]] && shift
  local msg="oskr save"
  while [[ $# -gt 0 ]]; do
    case "$1" in
      -m) [[ $# -ge 2 ]] || _setup_die "save: -m requires a message"; msg="$2"; shift 2 ;;
      *)  _setup_die "save: unknown flag '$1'" ;;
    esac
  done
  git -C "$ws" rev-parse --git-dir >/dev/null 2>&1 \
    || _setup_die "save: $ws is not a git repo — run git-init first"
  git -C "$ws" add -A
  if [[ -z "$(git -C "$ws" status --porcelain)" ]]; then
    echo "save: nothing to commit"
    return 0
  fi
  git -C "$ws" \
    -c user.email="${OSKR_GIT_EMAIL:-oskr@squirrlylabs.local}" \
    -c user.name="${OSKR_GIT_NAME:-oskr}" \
    commit -q -m "$msg"
}

# memory-link <workspace_dir> <name> [--from <dir>] — move a project's Claude Code
# auto-memory into the workspace repo (<ws>/memory/<name>/) so it travels with
# save + the workspace remote. Points the project at it via autoMemoryDirectory in
# its TRACKED .claude/settings.json, so worktrees and other machines pick it up.
# The pointer is ~/-relative when the workspace sits under $HOME (it assumes the
# same workspace path on every machine), else absolute. The old memory is copied
# (never moved) and only into an empty target, so re-runs never clobber.
# --from defaults to Claude Code's per-repo dir, keyed by the checkout path with
# `/` and `.` mapped to `-`. Commits nothing in either repo.
oskr_setup_memory_link() {
  [[ $# -ge 2 ]] || _setup_die "usage: memory-link <workspace_dir> <name> [--from <dir>]"
  local ws="$1" name="$2"; shift 2
  local from=""
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --from) [[ $# -ge 2 ]] || _setup_die "memory-link: --from requires a dir"; from="$2"; shift 2 ;;
      *) _setup_die "memory-link: unknown flag '$1'" ;;
    esac
  done
  ws="$(cd "$ws" && pwd)"
  local proj="$ws/projects/$name" mem="$ws/memory/$name" settings dir_ref
  [[ -d "$proj/.git" ]] || _setup_die "memory-link: projects/$name is not cloned"

  mkdir -p "$mem"
  [[ -n "$from" ]] \
    || from="${CLAUDE_CONFIG_DIR:-$HOME/.claude}/projects/$(printf '%s' "$proj" | tr '/.' '--')/memory"
  if [[ -d "$from" && -z "$(ls -A "$mem")" ]]; then
    cp -R "$from/." "$mem/"
  fi

  case "$mem" in
    "$HOME"/*) dir_ref="~/${mem#"$HOME"/}" ;;
    *)         dir_ref="$mem" ;;
  esac
  settings="$proj/.claude/settings.json"
  mkdir -p "$proj/.claude"
  [[ -f "$settings" ]] || printf '{}\n' > "$settings"
  jq --arg d "$dir_ref" '.autoMemoryDirectory = $d' "$settings" > "$settings.tmp" \
    && mv "$settings.tmp" "$settings"
}

# pull <workspace_dir> — bring the control plane (registry, brain, memory) up to
# date before working on this machine. Rebase + autostash so uncommitted memory
# edits ride along; a conflicting rebase stops and names the way out. Fetches
# only — never publishes.
oskr_setup_pull() {
  local ws="${1:-$PWD}"
  git -C "$ws" rev-parse --git-dir >/dev/null 2>&1 \
    || _setup_die "pull: $ws is not a git repo — run git-init first"
  git -C "$ws" \
    -c user.email="${OSKR_GIT_EMAIL:-oskr@squirrlylabs.local}" \
    -c user.name="${OSKR_GIT_NAME:-oskr}" \
    pull -q --rebase --autostash \
    || _setup_die "pull: rebase stopped — resolve in $ws, then git -C $ws rebase --continue"
}

cmd="${1:-}"; [[ "$#" -gt 0 ]] && shift
case "$cmd" in
  skeleton)     oskr_setup_skeleton "$@" ;;
  write-config) oskr_setup_write_config "$@" ;;
  bootstrap)    oskr_setup_bootstrap "$@" ;;
  git-init)     oskr_setup_git_init "$@" ;;
  rehydrate)    oskr_setup_rehydrate "$@" ;;
  save)         oskr_setup_save "$@" ;;
  memory-link)  oskr_setup_memory_link "$@" ;;
  pull)         oskr_setup_pull "$@" ;;
  *)            _setup_die "usage: oskr-setup.sh {skeleton|write-config|bootstrap|git-init|rehydrate|save|memory-link|pull} [workspace_dir] [--dry-run|--only <name>|-m <msg>|<name> --from <dir>]" ;;
esac
